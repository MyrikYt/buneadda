// ── Генерация карточки персонажа ──
function generateCard() {
  const rand = arr => arr[Math.floor(Math.random() * arr.length)];
  return {
    gender:     rand(BunkerData.genders),
    age:        18 + Math.floor(Math.random() * 52),
    size:       rand(BunkerData.sizes),
    profession: rand(BunkerData.professions),
    hobby:      rand(BunkerData.hobbies),
    health:     rand(BunkerData.health),
    trait:      rand(BunkerData.traits),
    phobia:     rand(BunkerData.phobias),
    extra:      rand(BunkerData.extras),
  };
}

// ── Цвет аватара по имени ──
function avatarColor(name) {
  let h = 0;
  for (const c of (name || 'X')) h = (h * 31 + c.charCodeAt(0)) % BunkerData.avatarColors.length;
  return BunkerData.avatarColors[Math.abs(h)];
}

// ── Первая буква имени ──
function avatarLetter(name) {
  return (name || '?')[0].toUpperCase();
}

// ── 4-символьный код комнаты ──
function roomCode() {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  let code = '';
  for (let i = 0; i < 4; i++) code += chars[Math.floor(Math.random() * chars.length)];
  return code;
}

// ── Время ──
function nowTime() {
  const d = new Date();
  return `${String(d.getHours()).padStart(2,'0')}:${String(d.getMinutes()).padStart(2,'0')}`;
}

